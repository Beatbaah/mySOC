"""
alerts/email_alert.py — SMTP email alert sender
"""

import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import List

import config
from utils.logger import get_logger

log = get_logger(__name__)


def send_email_alert(subject: str, body_html: str, recipients: List[str] = None) -> bool:
    if not config.SMTP_USER or not config.SMTP_PASSWORD:
        log.warning("SMTP credentials not configured — email alert skipped")
        return False

    to_list = recipients or config.ALERT_EMAIL_TO
    to_list = [r for r in to_list if r.strip()]
    if not to_list:
        return False

    try:
        msg = MIMEMultipart("alternative")
        msg["Subject"] = f"[MY SOC] {subject}"
        msg["From"]    = config.SMTP_FROM
        msg["To"]      = ", ".join(to_list)

        # Plain-text fallback
        plain = body_html.replace("<br>", "\n").replace("<b>", "").replace("</b>", "")
        msg.attach(MIMEText(plain, "plain"))
        msg.attach(MIMEText(body_html, "html"))

        with smtplib.SMTP(config.SMTP_HOST, config.SMTP_PORT, timeout=10) as server:
            server.ehlo()
            server.starttls()
            server.login(config.SMTP_USER, config.SMTP_PASSWORD)
            server.sendmail(config.SMTP_FROM, to_list, msg.as_string())

        log.info("Email alert sent: %s → %s", subject, to_list)
        return True

    except Exception as e:
        log.error("Email alert failed: %s", e)
        return False


def format_alert_email(alert: dict) -> tuple:
    """Return (subject, html_body) for an alert dict."""
    sev   = alert.get("severity", "UNKNOWN")
    atype = alert.get("alert_type", "UNKNOWN")
    desc  = alert.get("description", "")
    src   = alert.get("src_ip", "N/A")
    dst   = alert.get("dst_ip", "N/A")
    ts    = alert.get("timestamp", "N/A")

    subject = f"[{sev}] {atype} — {src}"
    html = f"""
    <html><body style="font-family:monospace;background:#0a0e1a;color:#e2e8f0;padding:20px">
    <h2 style="color:#00d4ff">⚠ MY SOC Alert</h2>
    <table style="border-collapse:collapse;width:100%">
      <tr><td style="padding:4px 8px"><b>Severity:</b></td><td style="color:{config.SEVERITY_LEVELS.get(sev,{}).get('color','#fff')}">{sev}</td></tr>
      <tr><td style="padding:4px 8px"><b>Type:</b></td><td>{atype}</td></tr>
      <tr><td style="padding:4px 8px"><b>Source IP:</b></td><td>{src}</td></tr>
      <tr><td style="padding:4px 8px"><b>Dest IP:</b></td><td>{dst}</td></tr>
      <tr><td style="padding:4px 8px"><b>Description:</b></td><td>{desc}</td></tr>
      <tr><td style="padding:4px 8px"><b>Timestamp:</b></td><td>{ts}</td></tr>
    </table>
    <p style="color:#666;font-size:11px">Generated by MY SOC v{config.APP_VERSION}</p>
    </body></html>
    """
    return subject, html
